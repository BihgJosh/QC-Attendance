function loadEnv(path) {
  if (!fs.existsSync(path)) return {};
  return Object.fromEntries(fs.readFileSync(path, "utf8").split(/\r?\n/).flatMap((rawLine) => {
    const line = rawLine.trim();
    if (!line || line.startsWith("#") || !line.includes("=")) return [];
    const equals = line.indexOf("=");
    let value = line.slice(equals + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) value = value.slice(1, -1);
    return [[line.slice(0, equals).trim(), value.replace(/\\n/g, "\n")]];
  }));
}

function escaped(title) {
  return `'${title.replace(/'/g, "''")}'`;
}

async function main() {
  const env = { ...loadEnv(".env"), ...loadEnv(".env.local") };
  const auth = new google.auth.JWT({
    email: env.GOOGLE_SERVICE_ACCOUNT_EMAIL,
    key: env.GOOGLE_PRIVATE_KEY,
    scopes: ["https://www.googleapis.com/auth/spreadsheets"],
  });
  const sheets = google.sheets({ version: "v4", auth });
  let metadata = await sheets.spreadsheets.get({
    spreadsheetId: SPREADSHEET_ID,
    fields: "sheets.properties(sheetId,title,gridProperties)",
  });
  const existing = new Map((metadata.data.sheets || []).map((sheet) => [sheet.properties.title, sheet.properties]));
  const requests = [];
  if (!existing.has("Dashboard")) {
    const blank = existing.get("Sheet1");
    if (!blank) throw new Error("Dashboard tab is missing and the original blank Sheet1 cannot be found.");
    requests.push({ updateSheetProperties: { properties: { sheetId: blank.sheetId, title: "Dashboard" }, fields: "title" } });
  }
  for (const title of ["Post Reports", "Timer Logs", "Observer Reports", "Generated Documents", "Email Log", "Activity Log"]) {
    if (!existing.has(title)) requests.push({ addSheet: { properties: { title, gridProperties: { rowCount: 2000, columnCount: title === "Timer Logs" ? 55 : 35 } } } });
  }
  if (requests.length) await sheets.spreadsheets.batchUpdate({ spreadsheetId: SPREADSHEET_ID, requestBody: { requests } });

  metadata = await sheets.spreadsheets.get({
    spreadsheetId: SPREADSHEET_ID,
    fields: "sheets.properties(sheetId,title,gridProperties)",
  });
  const tabs = new Map((metadata.data.sheets || []).map((sheet) => [sheet.properties.title, sheet.properties]));
  const definitions = [
    ["Post Reports", POST_HEADERS],
    ["Timer Logs", TIMER_HEADERS],
    ["Observer Reports", OBSERVER_HEADERS],
    ["Generated Documents", DOCUMENT_HEADERS],
    ["Email Log", EMAIL_HEADERS],
    ["Activity Log", ACTIVITY_HEADERS],
  ];
  for (const [title, headers] of definitions) {
    const current = await sheets.spreadsheets.values.get({ spreadsheetId: SPREADSHEET_ID, range: `${escaped(title)}!1:1` });
    const row = (current.data.values?.[0] || []).map((value) => String(value).trim());
    if (row.some(Boolean) && headers.some((header, index) => row[index] !== header)) {
      throw new Error(`"${title}" already contains incompatible headers. No existing data was changed.`);
    }
    if (!row.some(Boolean)) {
      await sheets.spreadsheets.values.update({
        spreadsheetId: SPREADSHEET_ID,
        range: `${escaped(title)}!A1`,
        valueInputOption: "RAW",
        requestBody: { values: [headers] },
      });
    }
  }

  const dashboardRows = [
    ["QC SERVICE REPORT DASHBOARD"],
    ["Live categorized reporting by service"],
    [],
    ["Service", "Post Reports", "Timer Logs", "Observer Reports", "Documents", "Email Shares", "Last Activity"],
    ...SERVICES.map((service, index) => {
      const row = index + 5;
      return [
        service,
        `=COUNTIF('Post Reports'!C:C,A${row})`,
        `=COUNTIF('Timer Logs'!C:C,A${row})`,
        `=COUNTIF('Observer Reports'!C:C,A${row})`,
        `=COUNTIF('Generated Documents'!C:C,A${row})`,
        `=COUNTIF('Email Log'!D:D,A${row})`,
        `=IF(COUNTIF('Activity Log'!D:D,A${row})=0,"No activity",MAXIFS('Activity Log'!B:B,'Activity Log'!D:D,A${row}))`,
      ];
    }),
    [],
    ["Use the category tabs below to filter by date, service, contributor or status. The Activity Log records every saved report and generated document."],
  ];
  await sheets.spreadsheets.values.update({
    spreadsheetId: SPREADSHEET_ID,
    range: "'Dashboard'!A1",
    valueInputOption: "USER_ENTERED",
    requestBody: { values: dashboardRows },
  });

  const formatRequests = [];
  for (const [title, headers] of definitions) {
    const properties = tabs.get(title);
    formatRequests.push(
      { updateSheetProperties: { properties: { sheetId: properties.sheetId, gridProperties: { frozenRowCount: 1 } }, fields: "gridProperties.frozenRowCount" } },
      { setBasicFilter: { filter: { range: { sheetId: properties.sheetId, startRowIndex: 0, endRowIndex: properties.gridProperties.rowCount, startColumnIndex: 0, endColumnIndex: headers.length } } } },
      { repeatCell: { range: { sheetId: properties.sheetId, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: headers.length }, cell: { userEnteredFormat: { backgroundColor: { red: 0.04, green: 0.12, blue: 0.28 }, textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true }, horizontalAlignment: "CENTER", wrapStrategy: "WRAP" } }, fields: "userEnteredFormat" } },
      { autoResizeDimensions: { dimensions: { sheetId: properties.sheetId, dimension: "COLUMNS", startIndex: 0, endIndex: headers.length } } },
    );
  }
  const dashboard = tabs.get("Dashboard");
  formatRequests.push(
    { updateSheetProperties: { properties: { sheetId: dashboard.sheetId, gridProperties: { frozenRowCount: 4 } }, fields: "gridProperties.frozenRowCount" } },
    { unmergeCells: { range: { sheetId: dashboard.sheetId, startRowIndex: 0, endRowIndex: 2, startColumnIndex: 0, endColumnIndex: 7 } } },
    { mergeCells: { range: { sheetId: dashboard.sheetId, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 7 }, mergeType: "MERGE_ALL" } },
    { mergeCells: { range: { sheetId: dashboard.sheetId, startRowIndex: 1, endRowIndex: 2, startColumnIndex: 0, endColumnIndex: 7 }, mergeType: "MERGE_ALL" } },
    { repeatCell: { range: { sheetId: dashboard.sheetId, startRowIndex: 0, endRowIndex: 1, startColumnIndex: 0, endColumnIndex: 7 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.04, green: 0.12, blue: 0.28 }, textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true, fontSize: 18 }, horizontalAlignment: "CENTER" } }, fields: "userEnteredFormat" } },
    { repeatCell: { range: { sheetId: dashboard.sheetId, startRowIndex: 3, endRowIndex: 4, startColumnIndex: 0, endColumnIndex: 7 }, cell: { userEnteredFormat: { backgroundColor: { red: 0.1, green: 0.35, blue: 0.55 }, textFormat: { foregroundColor: { red: 1, green: 1, blue: 1 }, bold: true } } }, fields: "userEnteredFormat" } },
    { autoResizeDimensions: { dimensions: { sheetId: dashboard.sheetId, dimension: "COLUMNS", startIndex: 0, endIndex: 7 } } },
  );
  await sheets.spreadsheets.batchUpdate({ spreadsheetId: SPREADSHEET_ID, requestBody: { requests: formatRequests } });
  const activity = await sheets.spreadsheets.values.get({
    spreadsheetId: SPREADSHEET_ID,
    range: "'Activity Log'!A:B",
  });
  if ((activity.data.values || []).length === 1) {
    const now = new Date().toISOString();
    await sheets.spreadsheets.values.append({
      spreadsheetId: SPREADSHEET_ID,
      range: "'Activity Log'!A:J",
      valueInputOption: "USER_ENTERED",
      insertDataOption: "INSERT_ROWS",
      requestBody: {
        values: [[randomUUID(), now, "", "All Services", "System", "Initialized", "Website integration", "Categorized service-report workbook connected", "", "Success"]],
      },
    });
  }
  console.log("QC Service Report Dashboard initialized with categorized tabs, filters and activity logging.");
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
